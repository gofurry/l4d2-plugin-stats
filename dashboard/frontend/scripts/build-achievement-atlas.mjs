import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const expectedArtworkKeys = [
  'career.veteran', 'career.survivor',
  'combat.scavenger', 'combat.special_hunter', 'combat.marksman', 'combat.team_hunt',
  'support.steadfast', 'support.defuser', 'support.field_medic',
  'boss.tank_hunter', 'boss.witch_hunter', 'boss.boss_nemesis',
  'versus.player_hunter', 'versus.infected_master', 'bond.comrade',
  'special.rock_breaker', 'special.one_shot', 'special.witch_nemesis', 'special.tongue_cutter',
  'special.defib_rescuer', 'special.miracle_healer',
  'secret.crashed', 'secret.see_u_again', 'secret.dispatch', 'secret.ff_king', 'secret.submissive',
]
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const assetRoot = path.join(root, 'src', 'assets', 'achievements')
const sourceRoot = path.join(assetRoot, 'source')
const generatedRoot = path.join(assetRoot, 'generated')
const manifest = JSON.parse(await readFile(path.join(assetRoot, 'artwork-manifest.json'), 'utf8'))

if (!Array.isArray(manifest) || manifest.length !== expectedArtworkKeys.length) throw new Error('artwork manifest must contain exactly 26 entries')
const keys = manifest.map(item => item.key)
const files = manifest.map(item => item.file)
if (new Set(keys).size !== keys.length) throw new Error('artwork manifest contains duplicate keys')
if (new Set(files).size !== files.length) throw new Error('artwork manifest contains duplicate files')
if (keys.some((key, index) => key !== expectedArtworkKeys[index])) throw new Error('artwork manifest order or catalog keys do not match Achievement Contract v1')
if (files.some(file => typeof file !== 'string' || !file.endsWith('.webp') || path.basename(file) !== file)) throw new Error('artwork manifest files must be plain WebP filenames')
const actualFiles = (await readdir(sourceRoot)).sort()
const expectedFiles = [...files].sort()
if (actualFiles.join('\n') !== expectedFiles.join('\n')) throw new Error('source directory contains missing or unlisted artwork')

const tileWidth = 128
const tileHeight = 128
const columns = 6
const rows = 5
const imageWidth = columns * tileWidth
const imageHeight = rows * tileHeight
const composites = []
const coordinates = {}
for (const [index, item] of manifest.entries()) {
  const source = path.join(sourceRoot, item.file)
  const metadata = await sharp(source).metadata()
  if (metadata.format !== 'webp' || metadata.width !== 256 || metadata.height !== 256) throw new Error(`${item.file} must be a 256x256 WebP source`)
  const left = (index % columns) * tileWidth
  const top = Math.floor(index / columns) * tileHeight
  const input = await sharp(source).resize(tileWidth, tileHeight, { fit: 'contain', kernel: sharp.kernel.lanczos3 }).webp({ quality: 86, alphaQuality: 100, effort: 6 }).toBuffer()
  composites.push({ input, left, top })
  coordinates[item.key] = { x: left, y: top, w: tileWidth, h: tileHeight }
}

await mkdir(generatedRoot, { recursive: true })
await sharp({ create: { width: imageWidth, height: imageHeight, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .webp({ quality: 86, alphaQuality: 100, effort: 6 })
  .toFile(path.join(generatedRoot, 'achievements-atlas.webp'))

const generated = `/* This file is generated by scripts/build-achievement-atlas.mjs. */
import atlasImage from './achievements-atlas.webp'

export const achievementAtlasImage = atlasImage
export const achievementAtlas = ${JSON.stringify({ imageWidth, imageHeight, tileWidth, tileHeight, items: coordinates }, null, 2)} as const
export type AchievementArtworkKey = keyof typeof achievementAtlas.items
`
await writeFile(path.join(generatedRoot, 'achievement-atlas.generated.ts'), generated, 'utf8')
console.log(`Built ${imageWidth}x${imageHeight} achievement atlas from ${manifest.length} sources.`)
